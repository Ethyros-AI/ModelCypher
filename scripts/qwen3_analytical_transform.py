# Analytical Transform: Derive T from Rules, Not Data
"""
WOLFRAM INSIGHT: The manifold is generated by RULES (weights).
We shouldn't sample it - we should DERIVE the transformation analytically.

The layer rule: h_out = h_in + Attention(h_in) + MLP(h_in + Attention(h_in))

This is fully specified by weights. The transformation T exists because
the rules define it - not because we fit it to data.

APPROACH:
1. Extract weight matrices for each layer
2. Compute the LINEAR COMPONENT of each operation
3. Compose to get analytical T
4. Compare to empirical T

If this works, we have the TRUE closed-form solution with no sampling.

Usage:
    python qwen3_analytical_transform.py --model /path/to/model
"""

from __future__ import annotations

import argparse
import logging
import numpy as np
from typing import Dict, List

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger(__name__)


def extract_layer_weights(model, layer_idx: int) -> Dict[str, np.ndarray]:
    """Extract weight matrices from a transformer layer."""
    import mlx.core as mx

    inner_model = model.model if hasattr(model, 'model') else model
    layer = inner_model.layers[layer_idx]

    weights = {}

    # Self-attention weights
    if hasattr(layer, 'self_attn'):
        attn = layer.self_attn

        # Query, Key, Value projections
        if hasattr(attn, 'q_proj'):
            weights['W_q'] = np.array(attn.q_proj.weight.astype(mx.float32)).T
        if hasattr(attn, 'k_proj'):
            weights['W_k'] = np.array(attn.k_proj.weight.astype(mx.float32)).T
        if hasattr(attn, 'v_proj'):
            weights['W_v'] = np.array(attn.v_proj.weight.astype(mx.float32)).T
        if hasattr(attn, 'o_proj'):
            weights['W_o'] = np.array(attn.o_proj.weight.astype(mx.float32)).T

        # Some models pack QKV
        if hasattr(attn, 'qkv_proj'):
            qkv = np.array(attn.qkv_proj.weight.astype(mx.float32)).T
            d = qkv.shape[1] // 3
            weights['W_q'] = qkv[:, :d]
            weights['W_k'] = qkv[:, d:2*d]
            weights['W_v'] = qkv[:, 2*d:]

    # MLP weights
    if hasattr(layer, 'mlp'):
        mlp = layer.mlp

        if hasattr(mlp, 'gate_proj'):
            weights['W_gate'] = np.array(mlp.gate_proj.weight.astype(mx.float32)).T
        if hasattr(mlp, 'up_proj'):
            weights['W_up'] = np.array(mlp.up_proj.weight.astype(mx.float32)).T
        if hasattr(mlp, 'down_proj'):
            weights['W_down'] = np.array(mlp.down_proj.weight.astype(mx.float32)).T

    # Layer norms
    if hasattr(layer, 'input_layernorm'):
        weights['ln1_weight'] = np.array(layer.input_layernorm.weight.astype(mx.float32))
    if hasattr(layer, 'post_attention_layernorm'):
        weights['ln2_weight'] = np.array(layer.post_attention_layernorm.weight.astype(mx.float32))

    return weights


def compute_attention_jacobian(weights: Dict[str, np.ndarray], hidden_dim: int,
                                n_heads: int, head_dim: int) -> np.ndarray:
    """
    Compute the LINEAR component of attention.

    For self-attention without context:
    h_out = softmax(Q @ K' / sqrt(d)) @ V @ W_o

    In the limit where attention is "uniform" (each position attended equally),
    this becomes a linear function. The Jacobian captures this linear component.

    For a single position attending only to itself:
    Attn(h) = h @ W_v @ W_o (since softmax([q·k]) = 1 for single token)

    This is EXACTLY linear: J_attn = W_v @ W_o
    """
    if 'W_v' in weights and 'W_o' in weights:
        W_v = weights['W_v']  # (hidden_dim, kv_dim) or similar
        W_o = weights['W_o']  # (hidden_dim, hidden_dim) or (kv_dim, hidden_dim)

        print(f"    W_v shape: {W_v.shape}, W_o shape: {W_o.shape}")

        # The shapes depend on the architecture
        # For standard attention: W_v (d, d), W_o (d, d)
        # For GQA: W_v (d, kv_dim), W_o (d, d)

        # Self-attention to own position: h -> h @ W_v @ W_o
        # Need to handle shape mismatch for GQA
        if W_v.shape[1] == W_o.shape[0]:
            J_attn = W_v @ W_o
        elif W_v.shape[1] < W_o.shape[0]:
            # GQA case: kv_dim < hidden_dim
            # The attention output goes through W_o which expects full hidden_dim
            # In GQA, the KV are repeated across head groups
            # Approximate: W_v (d, kv_dim), repeat to (d, d), then @ W_o
            n_groups = W_o.shape[0] // W_v.shape[1]
            W_v_expanded = np.tile(W_v, (1, n_groups))
            J_attn = W_v_expanded @ W_o
        else:
            # Fallback
            J_attn = np.zeros((hidden_dim, hidden_dim))

        return J_attn

    return np.zeros((hidden_dim, hidden_dim))


def compute_mlp_jacobian(weights: Dict[str, np.ndarray], hidden_dim: int) -> np.ndarray:
    """
    Compute the LINEAR component of the MLP.

    MLP: h_out = GELU(h @ W_gate) * (h @ W_up) @ W_down

    The GELU and element-wise multiply are nonlinear.
    But around the manifold mean, we can linearize.

    For GELU: GELU'(0) ≈ 0.5
    At the manifold mean, GELU'(mean activation) ≈ some constant α

    If we assume activations are roughly centered and GELU' ≈ 0.5:
    d(GELU(x))/dx ≈ 0.5 at x=0

    The Jacobian of GELU(Ax) @ B is approximately:
    (diag of GELU' at Ax) @ A @ B ≈ 0.5 * A @ B

    This is a rough approximation. The true Jacobian depends on the input.
    """
    if 'W_up' in weights and 'W_down' in weights:
        W_up = weights['W_up']      # (hidden_dim, intermediate_dim)
        W_down = weights['W_down']  # (intermediate_dim, hidden_dim)

        print(f"    W_up shape: {W_up.shape}, W_down shape: {W_down.shape}")

        # For SwiGLU: output = (h @ W_up * silu(h @ W_gate)) @ W_down
        # Linearization around zero: silu'(0) ≈ 0.5
        # So: d(output)/dh ≈ 0.5 * (W_up @ W_down + W_gate @ W_down)
        # (this is approximate since we ignore the product rule cross terms)

        # Match dimensions for matmul
        if W_up.shape[1] == W_down.shape[0]:
            J_mlp = 0.5 * W_up @ W_down
        else:
            # Shape mismatch - try transpose
            if W_up.shape[1] == W_down.shape[1]:
                J_mlp = 0.5 * W_up @ W_down.T
            elif W_up.shape[0] == W_down.shape[0]:
                J_mlp = 0.5 * W_up.T @ W_down
            else:
                print(f"    Warning: MLP shape mismatch, using zero Jacobian")
                J_mlp = np.zeros((hidden_dim, hidden_dim))

        return J_mlp

    return np.zeros((hidden_dim, hidden_dim))


def compute_layer_jacobian_analytical(model, layer_idx: int) -> np.ndarray:
    """
    Compute analytical Jacobian for a single layer.

    Layer: h_out = h_in + Attention(LN(h_in)) + MLP(LN(h_in + Attention(LN(h_in))))

    For simplicity, assume layer norms scale by constant (ignoring recentering).

    The Jacobian is approximately:
    J = I + J_attn + J_mlp

    (This assumes layer norms don't change the linear structure much)
    """
    import mlx.core as mx

    inner_model = model.model if hasattr(model, 'model') else model
    hidden_dim = inner_model.embed_tokens.weight.shape[1]

    # Get model config for attention parameters
    if hasattr(inner_model, 'config'):
        n_heads = getattr(inner_model.config, 'num_attention_heads', 32)
    else:
        n_heads = 32
    head_dim = hidden_dim // n_heads

    weights = extract_layer_weights(model, layer_idx)

    if not weights:
        print(f"  Warning: Could not extract weights for layer {layer_idx}")
        return np.eye(hidden_dim)

    # Compute component Jacobians
    J_attn = compute_attention_jacobian(weights, hidden_dim, n_heads, head_dim)
    J_mlp = compute_mlp_jacobian(weights, hidden_dim)

    # Residual structure: h_out = h_in + f(h_in)
    # J = I + J_f
    J_layer = np.eye(hidden_dim) + J_attn + J_mlp

    return J_layer, J_attn, J_mlp


def compute_multi_layer_jacobian(model, start_layer: int, end_layer: int) -> np.ndarray:
    """
    Compute analytical Jacobian for multiple consecutive layers.

    For layers L1, L2, ..., Lk with Jacobians J1, J2, ..., Jk:
    Total Jacobian = Jk @ Jk-1 @ ... @ J1

    For small deviations from identity (J_i ≈ I + ε_i):
    Total ≈ I + Σε_i (first order)
    """
    import mlx.core as mx

    inner_model = model.model if hasattr(model, 'model') else model
    hidden_dim = inner_model.embed_tokens.weight.shape[1]

    J_total = np.eye(hidden_dim)

    for layer_idx in range(start_layer, end_layer + 1):
        J_layer, _, _ = compute_layer_jacobian_analytical(model, layer_idx)
        J_total = J_layer @ J_total

    return J_total


def test_analytical_vs_empirical(model, tokenizer, start_layer: int, end_layer: int,
                                   test_prompts: List[str]) -> tuple:
    """Compare analytical Jacobian to empirical T."""
    import mlx.core as mx
    from mlx_lm.models.base import create_attention_mask

    inner_model = model.model if hasattr(model, 'model') else model
    hidden_dim = inner_model.embed_tokens.weight.shape[1]

    # Compute analytical Jacobian
    J_analytical = compute_multi_layer_jacobian(model, start_layer, end_layer)

    # Collect empirical (X, Y) pairs
    X_list = []
    Y_list = []

    for prompt in test_prompts:
        tokens = tokenizer.encode(prompt)
        if not tokens:
            tokens = [tokenizer.bos_token_id or 1]

        input_ids = mx.array([tokens])
        h = inner_model.embed_tokens(input_ids)
        mx.eval(h)
        mask = create_attention_mask(h, None)

        for idx, layer in enumerate(inner_model.layers):
            if idx == start_layer:
                x = np.array(h[0, -1, :].astype(mx.float32)).astype(np.float64)
                X_list.append(x)

            h = layer(h, mask, None)
            mx.eval(h)

            if idx == end_layer:
                y = np.array(h[0, -1, :].astype(mx.float32)).astype(np.float64)
                Y_list.append(y)
                break

    X = np.stack(X_list, axis=1)
    Y = np.stack(Y_list, axis=1)

    # Compute empirical T using our calibration approach
    X_mean = X.mean(axis=1, keepdims=True)
    Y_mean = Y.mean(axis=1, keepdims=True)
    X_c = X - X_mean
    Y_c = Y - Y_mean

    # Empirical T via least squares
    T_empirical = Y_c @ np.linalg.pinv(X_c)

    # Compare
    T_diff = np.linalg.norm(J_analytical - T_empirical) / np.linalg.norm(T_empirical)

    return J_analytical, T_empirical, T_diff, X, Y


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", type=str, required=True)
    parser.add_argument("--start", type=int, default=15)
    parser.add_argument("--end", type=int, default=20)
    args = parser.parse_args()

    import mlx.core as mx
    from mlx_lm import load

    logger.info("Loading model...")
    model, tokenizer = load(args.model)
    mx.eval(model.parameters())

    inner_model = model.model if hasattr(model, 'model') else model
    n_layers = len(inner_model.layers)
    hidden_dim = inner_model.embed_tokens.weight.shape[1]

    print(f"\n{'='*70}")
    print("ANALYTICAL TRANSFORM DERIVATION")
    print("Deriving T from rules (weights), not data")
    print("="*70)
    print(f"Model: {n_layers} layers, {hidden_dim} hidden dim")
    print(f"Analyzing layers {args.start} to {args.end}")

    # Analyze single layer first
    print(f"\n{'='*70}")
    print("SINGLE LAYER JACOBIAN ANALYSIS")
    print("="*70)

    for layer_idx in [args.start, (args.start + args.end) // 2, args.end]:
        print(f"\nLayer {layer_idx}:")
        J_layer, J_attn, J_mlp = compute_layer_jacobian_analytical(model, layer_idx)

        # Analyze structure
        print(f"  ||J - I|| / ||I||: {np.linalg.norm(J_layer - np.eye(hidden_dim)) / np.linalg.norm(np.eye(hidden_dim)):.4f}")
        print(f"  ||J_attn|| / ||I||: {np.linalg.norm(J_attn) / np.linalg.norm(np.eye(hidden_dim)):.4f}")
        print(f"  ||J_mlp|| / ||I||: {np.linalg.norm(J_mlp) / np.linalg.norm(np.eye(hidden_dim)):.4f}")

        # SVD of deviation from identity
        U, S, Vt = np.linalg.svd(J_layer - np.eye(hidden_dim), full_matrices=False)
        print(f"  Top 5 singular values of (J - I): {S[:5]}")

    # Compute multi-layer analytical Jacobian
    print(f"\n{'='*70}")
    print("MULTI-LAYER ANALYTICAL JACOBIAN")
    print("="*70)

    J_multi = compute_multi_layer_jacobian(model, args.start, args.end)
    print(f"Computed J for layers {args.start}-{args.end}")
    print(f"||J - I|| / ||I||: {np.linalg.norm(J_multi - np.eye(hidden_dim)) / np.linalg.norm(np.eye(hidden_dim)):.4f}")

    # SVD analysis
    U, S, Vt = np.linalg.svd(J_multi, full_matrices=False)
    print(f"Singular values of J: {S[:10]}...")
    print(f"Condition number: {S[0] / (S[-1] + 1e-10):.2e}")

    # Compare to empirical
    print(f"\n{'='*70}")
    print("ANALYTICAL vs EMPIRICAL COMPARISON")
    print("="*70)

    test_prompts = [
        "The capital of France is",
        "def fibonacci(n):",
        "What is the meaning of",
        "1 + 1 =",
        "Once upon a time",
        "The speed of light is",
        "Actually, I think",
        "SELECT * FROM users WHERE",
    ]

    J_analytical, T_empirical, T_diff, X, Y = test_analytical_vs_empirical(
        model, tokenizer, args.start, args.end, test_prompts
    )

    print(f"||J_analytical - T_empirical|| / ||T_empirical||: {T_diff:.4f}")
    print(f"  (0.0 = perfect match, analytical derivation is correct)")
    print(f"  (>0.1 = significant difference, linearization assumptions wrong)")

    # Test accuracy using analytical J
    print(f"\n{'='*70}")
    print("ACCURACY TEST: Analytical J vs Empirical T")
    print("="*70)

    held_out = [
        "The capital of Liechtenstein is",
        "99 + 87 =",
        "def binary_tree(",
        "The dragon breathed",
        "My favorite color is",
    ]

    # Test with analytical J
    for name, transform in [("Analytical J", J_analytical), ("Empirical T", T_empirical)]:
        matches = 0
        for prompt in held_out:
            tokens = tokenizer.encode(prompt)
            input_ids = mx.array([tokens])

            # Normal forward
            logits = model(input_ids)
            mx.eval(logits)
            normal_token = int(np.argmax(np.array(logits[0, -1, :].astype(mx.float32))))

            # Transform-based forward
            h = inner_model.embed_tokens(input_ids)
            mx.eval(h)
            from mlx_lm.models.base import create_attention_mask
            mask = create_attention_mask(h, None)

            for idx, layer in enumerate(inner_model.layers):
                if idx == args.start:
                    h_in = np.array(h[0, -1, :].astype(mx.float32)).astype(np.float64)
                    h_out = transform @ h_in  # No centering for analytical

                    h_np = np.array(h.astype(mx.float32))
                    h_np[0, -1, :] = h_out.astype(np.float32)
                    h = mx.array(h_np).astype(h.dtype)
                    mx.eval(h)
                elif args.start < idx <= args.end:
                    pass
                else:
                    h = layer(h, mask, None)
                    mx.eval(h)

            h = inner_model.norm(h)
            if hasattr(model, 'lm_head'):
                logits = model.lm_head(h)
            else:
                logits = inner_model.embed_tokens.as_linear(h)
            mx.eval(logits)
            t_token = int(np.argmax(np.array(logits[0, -1, :].astype(mx.float32))))

            if normal_token == t_token:
                matches += 1

        print(f"{name}: {matches}/{len(held_out)} ({100*matches/len(held_out):.0f}%)")

    # Conclusion
    print(f"\n{'='*70}")
    print("INSIGHT")
    print("="*70)
    print(f"""
If T_diff is small (~0), the analytical derivation matches empirical.
This would mean: T can be computed from WEIGHTS ALONE, no sampling needed.

Current T_diff: {T_diff:.4f}

The gap (if any) comes from:
1. Layer norm effects (we ignored recentering)
2. GELU/softmax linearization errors
3. Attention pattern dependence on input

To close the gap:
- Account for average attention patterns
- Use actual activation statistics for GELU linearization
- Include layer norm Jacobians properly

The RULE is fully specified by weights. We just need to read it correctly.
""")


if __name__ == "__main__":
    main()
